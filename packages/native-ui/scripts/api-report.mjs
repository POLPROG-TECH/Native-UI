#!/usr/bin/env node
/**
 * Public API report: every name exported from `src/index.ts` with its kind
 * and resolved type, written to `api/native-ui.api.md`. `--check` compares
 * against the committed report and fails on any difference, so an API change
 * is always a reviewed diff (and a deliberate semver decision).
 *
 * Usage: node scripts/api-report.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = path.join(ROOT, 'src/index.ts');
const REPORT = path.join(ROOT, 'api/native-ui.api.md');
const FORMAT = ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.WriteArrowStyleSignature;

function createChecker() {
  const configPath = path.join(ROOT, 'tsconfig.build.json');
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, ROOT);
  const program = ts.createProgram({ rootNames: [ENTRY], options: parsed.options });

  return { program, checker: program.getTypeChecker() };
}

/**
 * TypeScript prints union members in creation order, which can differ between
 * runs; sorting them keeps the report stable so `--check` only fails on real
 * API changes.
 */
function formatType(checker, type, location, flags = FORMAT, expandAlias = false) {
  if (!type.isUnion() || (type.aliasSymbol && !expandAlias)) {
    return checker.typeToString(type, location, flags);
  }

  return type.types
    .map((member) => checker.typeToString(member, location, flags))
    .sort()
    .join(' | ');
}

function resolveSymbol(checker, symbol) {
  return symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
}

function describeMembers(checker, type, location) {
  return checker
    .getPropertiesOfType(type)
    .map((member) => {
      const optional = member.flags & ts.SymbolFlags.Optional ? '?' : '';
      const memberType = checker.getTypeOfSymbolAtLocation(member, location);

      return `  ${member.getName()}${optional}: ${formatType(checker, memberType, location)};`;
    })
    .sort();
}

function describeExport(checker, name, symbol) {
  const target = resolveSymbol(checker, symbol);
  const declaration = target.declarations?.[0];

  if (!declaration) {
    return `export ${name}: unknown;`;
  }

  if (ts.isInterfaceDeclaration(declaration)) {
    const members = describeMembers(checker, checker.getDeclaredTypeOfSymbol(target), declaration);

    return [`export interface ${name} {`, ...members, '}'].join('\n');
  }

  if (ts.isTypeAliasDeclaration(declaration) || ts.isEnumDeclaration(declaration)) {
    const type = checker.getDeclaredTypeOfSymbol(target);
    const flags = FORMAT | ts.TypeFormatFlags.InTypeAlias;

    return `export type ${name} = ${formatType(checker, type, declaration, flags, true)};`;
  }

  const valueType = checker.getTypeOfSymbolAtLocation(target, declaration);

  return `export const ${name}: ${formatType(checker, valueType, declaration)};`;
}

function buildReport() {
  const { program, checker } = createChecker();
  const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(ENTRY));
  const entries = checker
    .getExportsOfModule(moduleSymbol)
    .map((symbol) => describeExport(checker, symbol.getName(), symbol))
    .sort((a, b) => a.localeCompare(b));

  return [
    '<!-- Generated by scripts/api-report.mjs. Do not edit by hand. -->',
    '',
    '```ts',
    ...entries,
    '```',
    '',
  ].join('\n');
}

function firstDifference(expected, actual) {
  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  const index = actualLines.findIndex((line, i) => line !== expectedLines[i]);

  return index === -1 ? expectedLines.length : index;
}

function check(report) {
  const committed = fs.existsSync(REPORT) ? fs.readFileSync(REPORT, 'utf8') : '';

  if (committed === report) {
    console.log('Public API matches api/native-ui.api.md.');

    return;
  }

  const line = firstDifference(committed, report) + 1;
  console.error(`Public API changed (first difference at line ${line} of the report).`);
  console.error(
    'Run "npm run api:report" and commit api/native-ui.api.md if the change is intended.',
  );
  process.exit(1);
}

const report = buildReport();

if (process.argv.includes('--check')) {
  check(report);
} else {
  fs.mkdirSync(path.dirname(REPORT), { recursive: true });
  fs.writeFileSync(REPORT, report);
  console.log(`Wrote ${path.relative(ROOT, REPORT)}.`);
}
